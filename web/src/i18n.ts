export function localizeMessage(message:string,language:'中文'|'English'):string{
 if(!message)return '';
 if(language==='中文')return message;
 const status=message.match(/\s*[（(]HTTP (\d{3})[）)]$/);
 const text=status?message.slice(0,status.index):message;
 const translated=diagnostics[text]||( /\p{Script=Han}/u.test(text)?'The request could not be completed. Your inquiry is preserved.':text);
 return translated+(status?` (HTTP ${status[1]})`:'');
}
export function cachedRecord(messages:{role:string;content:string}[],draft:string,language:'中文'|'English'):string{
 const zh=language==='中文';
 return [zh?'# Inquire — 本地保留记录':'# Inquire — Cached inquiry',
  zh?'\n后台会话不可用；以下为浏览器中保留的用户陈述与模型追问，不是伦理结论。':'\nThe backend session is unavailable. These cached statements and questions are not ethical conclusions.',
  ...messages.map(m=>`\n## ${m.role==='user'?(zh?'用户陈述':'User statement'):'Inquire'}\n\n${m.content}`),
  `\n## ${zh?'未发送草稿':'Unsent draft'}\n\n${draft}`].join('\n');
}
